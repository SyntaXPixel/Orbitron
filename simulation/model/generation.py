"""Onboard data generation model for virtual satellites.

Maintains monotonic generation counters across simulation intervals and
supports fractional byte credits across subsecond ticks without double-counting.
"""

from __future__ import annotations

from typing import Optional
from pydantic import BaseModel


class SatelliteGenerationProfile(BaseModel):
    """Configuration profile for satellite data generation."""
    generation_rate_bytes_per_second: int = 1_000_000  # Default 1 MB/s
    initial_backlog_bytes: int = 0
    continues_during_comms_fault: bool = True  # Scientific instruments continue collecting data during RF comms fault


class SatelliteDataGenerator:
    """Manages data generation for a single virtual satellite."""

    def __init__(self, satellite_id: str, profile: Optional[SatelliteGenerationProfile] = None):
        self.satellite_id = satellite_id
        self.profile = profile or SatelliteGenerationProfile()
        self.generated_bytes_total: int = 0
        self._fractional_credit: float = 0.0

    def advance(self, elapsed_seconds: float, in_comms_fault: bool = False) -> int:
        """Advance simulation time and return newly generated bytes.

        Monotonically advances generated_bytes_total.
        """
        if elapsed_seconds <= 0:
            return 0

        if in_comms_fault and not self.profile.continues_during_comms_fault:
            return 0

        # Calculate newly produced bytes with fractional credit accumulation
        exact_bytes = (self.profile.generation_rate_bytes_per_second * elapsed_seconds) + self._fractional_credit
        new_bytes = int(exact_bytes)
        self._fractional_credit = exact_bytes - new_bytes

        self.generated_bytes_total += new_bytes
        return new_bytes

    def set_counter(self, committed_total: int) -> None:
        """Restore monotonic counter from accepted backend checkpoint."""
        if committed_total >= self.generated_bytes_total:
            self.generated_bytes_total = committed_total
            self._fractional_credit = 0.0
